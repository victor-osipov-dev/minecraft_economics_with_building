export function typeName(typeId) {
  const e = STR[lang].types && STR[lang].types[typeId];
  return (e && e[0]) || (STR.ru.types[typeId] && STR.ru.types[typeId][0]) || typeId;
}
export function typeDesc(typeId) {
  const e = STR[lang].types && STR[lang].types[typeId];
  return (e && e[1]) || (STR.ru.types[typeId] && STR.ru.types[typeId][1]) || "";
}
export function tierName(tier) {
  return (STR[lang].tiers && STR[lang].tiers[tier]) || STR.ru.tiers[tier] || "";
}
export function mstoneName(id) {
  for (const m of [{ id: "m50" }, { id: "m200" }, { id: "m500" }, { id: "m1000" }]) {
    if (m.id === id) {
      const map = STR[lang].mstones || {};
      return map[id] || STR.ru.mstones[id] || id;
    }
  }
  return id;
}
