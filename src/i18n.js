// Все варианты имени блока (оба языка) — для поиска по панели блоков.
export function blockNameSearch(id) {
  const a = STR[lang].blockNames && STR[lang].blockNames[id];
  const b = STR.ru.blockNames && STR.ru.blockNames[id];
  const c = STR.en.blockNames && STR.en.blockNames[id];
  return a === b ? (a || "") : ((a || "") + " " + (b || "") + " " + (c || ""));
}
